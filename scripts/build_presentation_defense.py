def build(evidence, is_draft):
    texts, counts = speech(evidence)
    elapsed = 0
    records = []
    out = ["# Доклад и вопросы к защите WorldWeaver 1.2", ""]
    if is_draft:
        out += ["> ВНУТРЕННИЙ ЧЕРНОВИК. Окончательный срез программных и дополнительных испытаний ещё не утверждён. Это не итоговый документ для защиты.", ""]
    total = sum(len(words(t)) for t in texts)
    ru_total = sum(len(russian_words(t)) for t in texts)
    out += ["## Только произносимый доклад — 8:40", "",
            f"12 слайдов; {total} лексических слов, из них {ru_total} слов с кириллицей. Средний темп с учётом пауз — {total / (520 / 60):.1f} слова в минуту. Числа в речевом тексте записаны словами. Заголовки, инструкции и банк вопросов в этот счёт не входят.",
            "", "Переходы привязаны к накопленному времени. Не нужно читать названия исходных классов и SHA вслух. На изображениях показывайте указателем фактическое состояние, не ожидайте новую долгую генерацию во время доклада.", ""]
    for i, (title, seconds, text) in enumerate(zip(TITLES, TIMES, texts), 1):
        start = elapsed
        elapsed += seconds
        count = len(words(text))
        records.append({"slide": i, "title": title, "start_seconds": start,
                        "end_seconds": elapsed, "allocated_seconds": seconds,
                        "spoken_words": count, "cyrillic_words": len(russian_words(text)),
                        "words_per_minute": round(count / (seconds / 60), 1)})
        out += [f"### {i}. {title} · {timestamp(start)}–{timestamp(elapsed)}", "", text, ""]
    out += ["---", "", "## Вопросы комиссии — вне времени доклада", "",
            "Следующий раздел предназначен для подготовки ответов. Он не произносится как продолжение доклада 8:40. Цифры и пути сверяйте с приложенными финальными протоколами.", ""]
    for i, (question, answer) in enumerate(questions(), 1):
        out += [f"### Вопрос {i}. {question}", "", answer, ""]
    out += ["## Протоколы и условия перед защитой", ""]
    paths = [(r["path"], r["label"]) for r in evidence["testRuns"]]
    paths += [(r["path"], r["label"]) for r in evidence.get("checkRuns", [])]
    paths += [(r["path"], r["label"] + " —с собственным срезом исходников") for r in evidence["modelRuns"]]
    paths += [(r["path"], "Отдельное наблюдение/проверка") for r in evidence.get("observations", [])]
    seen = set()
    for name, label in paths:
        if name not in seen:
            out.append(f"- {label}: [{name}](../{name}).")
            seen.add(name)
    out += ["", "Руководство настройки: [свой API](../docs/custom-api.md), [архитектура и границы](../docs/agent-architecture-and-limits.md), [условия испытаний](../docs/research/chat-agent-test-summary.md).",
            "", "Для репетиции: откройте 12 слайдов, запустите таймер и прочитайте только первый раздел. После 8:40 остановите таймер. Уточните формулировки собственного вклада и административные сведения по требованиям кафедры.", ""]
    metadata = {"slides": 12, "planned_seconds": 520, "planned_duration": "8:40",
                "spoken_words": total, "spoken_cyrillic_words": ru_total,
                "average_words_per_minute": round(total / (520 / 60), 2),
                "word_count_method": "Unicode lexical tokens, hyphenated words count as one; Cyrillic subset counted separately; speech paragraphs only. Numerals in main speech are spelled out.",
                "question_bank_count": len(questions()), "question_bank_included_in_timing": False,
                "segments": records, "source_counts": {"edit": counts[:2], "play": counts[2:4], "model": counts[4:]},
                "draft": is_draft}
    if not 1000 <= total <= 1200:
        raise ValueError(f"Speech length requires adjustment: {total}words, expected1000–1200.")
    if not all(80 <= r["words_per_minute"] <= 155 for r in records):
        raise ValueError("At least one slide requires implausible speech pace.")
    return "\n".join(out), metadata


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence", default="results/presentation-evidence-1.2.json")
    parser.add_argument("--output", default="deliverables/Доклад_и_вопросы_WorldWeaver.md")
    parser.add_argument("--metadata", default=".private/presentation-1.2/defense-meta.json")
    parser.add_argument("--draft", action="store_true")
    args = parser.parse_args()
    evidence, evidence_sha = read_evidence(args.evidence)
    if evidence.get("version") != "1.2":
        raise ValueError("Expected1.2 evidence.")
    destination = (ROOT / args.output).resolve()
    if args.draft and not destination.is_relative_to(ROOT / ".private"):
        raise ValueError("Draft defense may be written only under.private.")
    if not args.draft and evidence.get("finalized") is not True:
        raise ValueError("Final cutoff not authorized: evidence.finalized is not true.")
    text, metadata = build(evidence, args.draft)
    metadata.update({"generatedUtc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
                     "evidence": args.evidence, "evidence_sha256": evidence_sha,
                     "output": str(destination), "output_sha256": digest(text.encode()),
                     "generator_sha256": digest(Path(__file__).read_bytes())})
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text)
    meta_path = ROOT / args.metadata
    meta_path.parent.mkdir(parents=True, exist_ok=True)
    meta_path.write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({k: metadata[k] for k in ["slides", "planned_seconds", "spoken_words", "spoken_cyrillic_words", "average_words_per_minute", "question_bank_count", "draft"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()

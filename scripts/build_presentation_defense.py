def digest(data):
    return hashlib.sha256(data).hexdigest()


def ru_number(number):
    if not 0 <= number <= 999:
        return str(number)
    ones = ["ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]
    teens = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
             "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
    tens = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
            "семьдесят", "восемьдесят", "девяносто"]
    hundreds = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
                "семьсот", "восемьсот", "девятьсот"]
    if number == 0:
        return ones[0]
    result = [hundreds[number // 100]] if number >= 100 else []
    tail = number % 100
    if 10 <= tail < 20:
        result.append(teens[tail - 10])
    else:
        if tail >= 20:
            result.append(tens[tail // 10])
        if tail % 10:
            result.append(ones[tail % 10])
    return " ".join(result)


def words(text):
    # Unicode lexical words; hyphenated forms count as one. English API terms count.
    return re.findall(r"[^\W_]+(?:[-’'][^\W_]+)*", text, re.UNICODE)


def russian_words(text):
    return re.findall(r"\b[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*\b", text)


def timestamp(seconds):
    return f"{seconds // 60}:{seconds % 60:02}"


def read_evidence(name):
    path = ROOT / name
    data = path.read_bytes()
    return json.loads(data), digest(data)


def xml_counts(name):
    node = ET.parse(ROOT / name).getroot()
    if not node.get("end-time"):
        raise ValueError("Unfinished NUnit protocol: " + name)
    return int(node.get("passed")), int(node.get("total"))


